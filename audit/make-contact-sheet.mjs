/**
 * audit/make-contact-sheet.mjs — write audit/contact-sheet.html.
 *
 * Lists the screenshots the audit just took for a handful of representative
 * routes, phone next to desktop, so the layout can be reviewed by eye rather
 * than only through metrics. Re-run it after every audit run.
 *
 * Usage: node audit/make-contact-sheet.mjs
 */
import fs from "node:fs";
import path from "node:path";

const SHOTS = path.join(process.cwd(), "audit", "screenshots");
const WIDTHS = ["mobile", "desktop"];

const PAGES = [
  ["Home", "home-"],
  ["Collections", "collections-871"],
  ["A collection", "collections-gold-jewellery-"],
  ["A product", "products-classic-gold-ring-demo-"],
  ["Gems", "gems-"],
  ["Rates", "rates-815"],
  ["Rate history", "rates-history-"],
  ["Rate calculator", "rates-calculator-"],
  ["Guides", "guides-"],
  ["About", "about-"],
  ["Visit us", "visit-us-"],
  ["Contact", "contact-"],
  ["Wishlist (empty state)", "wishlist-"],
  ["Admin dashboard", "admin-59"],
  ["Admin sign-in", "admin-login-"],
  ["404", "this-page-does-not-exist-audit-"],
];

const files = Object.fromEntries(
  WIDTHS.map((w) => {
    const dir = path.join(SHOTS, w);
    return [w, fs.existsSync(dir) ? fs.readdirSync(dir) : []];
  }),
);

const pick = (prefix, width) => files[width].find((f) => f.startsWith(prefix));

const blocks = [];
for (const [label, prefix] of PAGES) {
  const cards = WIDTHS.map((width) => {
    const file = pick(prefix, width);
    if (!file) return "";
    return `<figure class="${width === "mobile" ? "phone" : "wide"}">
      <figcaption>${label} — ${width}</figcaption>
      <img loading="lazy" src="screenshots/${width}/${file}" alt="${label} at ${width} width" />
    </figure>`;
  }).join("");
  blocks.push(`<h2>${label}</h2><div class="row">${cards || "<em>no screenshot</em>"}</div>`);
}

const html = `<!doctype html>
<!-- Generated by audit/make-contact-sheet.mjs — do not edit by hand. -->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <title>Audit contact sheet</title>
    <style>
      body { font: 14px/1.5 system-ui, sans-serif; margin: 0; padding: 24px; background: #241f1a; color: #f2ece1; }
      h1 { font-family: Georgia, serif; }
      h2 { font-family: Georgia, serif; margin: 32px 0 12px; color: #e8c987; }
      .row { display: flex; gap: 16px; overflow-x: auto; padding-bottom: 12px; }
      figure { margin: 0; flex: 0 0 auto; }
      figcaption { font-size: 12px; color: #c9bfae; margin-bottom: 6px; }
      img { display: block; border: 1px solid #4a4038; background: #fff; }
      .phone img { width: 300px; }
      .wide img { width: 640px; }
    </style>
  </head>
  <body>
    <h1>Audit contact sheet</h1>
    <p>Phone (390 px) and desktop (1440 px) for each representative page. Full-page captures, so they are tall — scroll each row sideways.</p>
    ${blocks.join("\n")}
  </body>
</html>
`;

fs.writeFileSync(path.join(process.cwd(), "audit", "contact-sheet.html"), html);
console.log("Wrote audit/contact-sheet.html");
