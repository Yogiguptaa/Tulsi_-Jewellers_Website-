#!/usr/bin/env python3
"""Zip the site source for GitHub, excluding local and secret files.

    python scripts/package-site.py

Writes tulsi-jewellers-website.zip next to the project root, with every path
inside a single ``tulsi-jewellers/`` folder. Local state that a fresh clone does
not need (node_modules, .next, .git, logs, .data, .env.local) never goes in.
``next-env.d.ts`` is included on purpose: it is git-ignored, but a fresh checkout
needs it for `npm run check:types` before the first `next build`.
"""

from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tulsi-jewellers-website.zip"
PREFIX = "tulsi-jewellers"

SKIP_DIRS = {
    "node_modules",
    ".next",
    ".git",
    ".data",
    ".freebuff",
    ".scratch",
    ".vercel",
    ".open-next",
    ".wrangler",
    "freebuff-sites-build",
    "coverage",
    "screenshots",
}
SKIP_SUFFIXES = (".log", ".tsbuildinfo")
SKIP_FILES = {
    ".DS_Store",
    OUT.name,
    # Regenerated by the Sites build on every publish.
    "freebuff.wrangler.jsonc",
    "freebuff.open-next.config.ts",
}
# Generated by the browser audit: ~480 MB of screenshots and reports that a
# fresh clone neither needs nor could push to GitHub. The audit's own scripts
# and written summaries stay in.
SKIP_PATHS = {
    "audit/screenshots",
    "audit/report.json",
    "audit/report.focus.json",
    "audit/contact-sheet.html",
}
# Never ship secrets; .env.example is the documented template and is allowed.
SKIP_ENV_EXCEPTIONS = {".env.example", ".env.sample", ".env.template"}

count = 0
with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
    for path in sorted(ROOT.rglob("*")):
        rel = path.relative_to(ROOT)
        if path.is_dir():
            continue
        if any(part in SKIP_DIRS for part in rel.parts):
            continue
        if any(rel.as_posix() == p or rel.as_posix().startswith(p + "/") for p in SKIP_PATHS):
            continue
        if path.name in SKIP_FILES or path.name.endswith(SKIP_SUFFIXES):
            continue
        if (path.name.startswith(".env") and path.name not in SKIP_ENV_EXCEPTIONS):
            continue
        zf.write(path, f"{PREFIX}/{rel.as_posix()}")
        count += 1

print(f"{OUT.name}: {count} files, {OUT.stat().st_size / 1_048_576:.1f} MB")
